#!/usr/bin/env python3
# genprof.py <out.cpp> <lo> <hi> [exclude...]: wrappers for every recompiled
# function in [lo, hi) (study/hle-renderer instrumentation, see
# runtime/debug/d3d_profile.h), except the excluded ones, which are already
# hooked elsewhere and call d3dprof::Scope themselves.
import pickle, sys
funcs, insns, calls, callees = pickle.load(open('/work/hle/xref.pkl', 'rb'))
out, lo, hi = sys.argv[1], int(sys.argv[2], 16), int(sys.argv[3], 16)
excl = set(int(x.replace('sub_', ''), 16) for x in sys.argv[4:])
fs = [f for f in funcs if lo <= f < hi]
with open(out, 'w') as o:
    o.write('// Generated by genprof.py (study/hle-renderer only): a counting wrapper\n')
    o.write('// for each recompiled function in the D3D library range.\n')
    o.write('#include <stdafx.h>\n#include "d3d_profile.h"\n\n')
    o.write('namespace d3dprof\n{\n')
    o.write(f'    const uint32_t g_addrs[{len(fs)}] = {{\n')
    for i in range(0, len(fs), 8):
        o.write('        ' + ', '.join(f'0x{f:08X}' for f in fs[i:i + 8]) + ',\n')
    o.write('    };\n')
    o.write(f'    const size_t g_count = {len(fs)};\n}}\n\n')
    for i, f in enumerate(fs):
        if f in excl:
            continue
        mk = 'D3DPROF_MAKESPACE' if f == 0x82597070 else 'D3DPROF_WRAP'
        o.write(f'{mk}({i}, sub_{f:08X})\n')
print(f'{len(fs)} functions, {len(excl)} excluded')
